function areas = frontal_occipital_areas()
%FRONTAL_OCCIPITAL_AREAS The two areas of the area tests, using drawn map electrodes only.
%   Frontal: every drawn electrode of the Fp, AF, F and FC rows. Occipital: the three drawn
%   occipital and parieto-occipital electrodes. A child needs minElectrodes usable
%   electrodes in an area to count there.
    areas = struct( ...
        'name', {"Frontal", "Occipital"}, ...
        'channels', {["Fp1" "Fpz" "Fp2" "AF7" "AF3" "AF4" "AF8" "F5" "F3" "F1" "F2" "F4" "F6" "F8" ...
                      "FC3" "FC1" "FC2" "FC4" "FC6"], ["PO7" "O1" "O2"]}, ...
        'minElectrodes', {3, 2});
end
